// 핵심콕콕 박스 데이터 (키-값 9개)
export type KeyFacts = Record<string, string>;

// Q&A 카드 데이터
export interface QAItem {
  q: string;       // 질문
  a: string;       // 답변 본문
  highlights?: string[]; // 형광펜으로 강조할 단어들
  table?: {
    headers: string[];
    rows: string[][];
  };
}

// 정책 데이터 확장 인터페이스
export interface PolicyExtension {
  type: PolicyType;
  keyFacts: KeyFacts;
  keyFactsHighlights?: Record<string, string[]>;
  qa: QAItem[];
}

